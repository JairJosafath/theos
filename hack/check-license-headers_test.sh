#!/usr/bin/env bash
# Tests for hack/check-license-headers.sh and the files that name theos's
# license (#47): every Go file of the repository carries the Apache-2.0
# header, LICENSE is the Apache License 2.0, NOTICE names the authors, and
# the UI's package and the chart say Apache-2.0; a Go file without the
# header, or with another one, fails with its path, and one under templates/
# is left alone.
# Run: hack/check-license-headers_test.sh
T=$(mktemp -d)
trap 'rm -rf "$T"' EXIT
ROOT=$(cd "$(dirname "$0")/.." && pwd)
CHECK=$ROOT/hack/check-license-headers.sh
fail=0
check() { if [ "$2" = "$3" ]; then echo "ok   $1"; else echo "FAIL $1: got [$2] want [$3]"; fail=1; fi; }

out=$("$CHECK" "$ROOT" 2>&1)
check "every Go file of the repository has the license header (#47)" "$?" 0
[ -z "$out" ] || echo "$out" | head -20

check "LICENSE is the Apache License 2.0" "$(grep -c '^ *Apache License$' "$ROOT/LICENSE")" 1
check "LICENSE says version 2.0" "$(grep -c 'Version 2.0, January 2004' "$ROOT/LICENSE")" 1
check "LICENSE grants no rights back to one holder alone" "$(grep -ci 'all rights reserved' "$ROOT/LICENSE")" 0
check "NOTICE names the authors" "$(grep -c '^Copyright 2026 The theos Authors$' "$ROOT/NOTICE")" 1
check "the boilerplate is the Apache-2.0 header" \
  "$(grep -c 'Licensed under the Apache License, Version 2.0' "$ROOT/hack/boilerplate.go.txt")" 1
check "the boilerplate keeps YEAR for controller-gen" "$(grep -c '^Copyright YEAR The theos Authors\.$' "$ROOT/hack/boilerplate.go.txt")" 1
check "the UI's package says Apache-2.0" "$(grep -c '^  "license": "Apache-2.0",$' "$ROOT/ui/package.json")" 1
check "the chart says Apache-2.0" "$(grep -c 'artifacthub.io/license: Apache-2.0' "$ROOT/dist/chart/Chart.yaml")" 1
check "nothing of theos's own says proprietary" \
  "$(cd "$ROOT" && git grep -il 'which is proprietary\|theos is proprietary' -- ':!docs/plans/done' ':!docs/design-history.md' ':!docs/screenshots' ':!hack/check-license-headers_test.sh' | wc -l)" 0

header=$(sed 's/YEAR/2026/' "$ROOT/hack/boilerplate.go.txt")
tree() {
  rm -rf "$T/r" && mkdir -p "$T/r/internal/x" "$T/r/templates/go-cli" && git -C "$T/r" init -q
}
run() {
  git -C "$T/r" add -A
  out=$("$CHECK" "$T/r" 2>&1)
  rc=$?
}

tree
printf '%s\n\npackage x\n' "$header" >"$T/r/internal/x/a.go"
printf '//go:build !ignore_autogenerated\n\n%s\n\npackage x\n' "$header" >"$T/r/internal/x/zz_generated.go"
run
check "a file with the header passes, after a build constraint too" "$rc" 0

tree
printf 'package x\n' >"$T/r/internal/x/bare.go"
run
check "a Go file without the header fails (#47)" "$rc" 1
check "it names the file" "$(grep -c '^internal/x/bare.go: no license header' <<<"$out")" 1

tree
printf '/*\nCopyright 2026 Someone. All rights reserved.\n*/\n\npackage x\n' >"$T/r/internal/x/other.go"
run
check "a Go file with another header fails" "$rc" 1

tree
printf 'package main\n' >"$T/r/templates/go-cli/main.go"
run
check "a template's Go file is someone else's application" "$rc" 0

exit $fail
