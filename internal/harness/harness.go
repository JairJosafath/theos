// Package harness is the interface an agent tool implements to play the
// lead runtime's roles (docs/plans/lead-runtime.md, decision 7): its name,
// the value of Agent.spec.harness, and what it can do. What more a harness
// does is an optional interface a caller asks for, never a harness asked
// for by name. Level 0 is any MCP client, with no code; level 1 renders
// the lead's files (LeadFiles).
package harness

import (
	"bytes"
	"errors"
	"io/fs"

	"github.com/JairJosafath/theos/internal/method"
)

// Capabilities is what a harness can do.
type Capabilities struct {
	// Subagents means a session starts others for the roles; Parallel that
	// they run at once.
	Subagents, Parallel bool
	// ModelPerRole means each role's subagent runs on its Agent's model.
	ModelPerRole bool
	// MCP means the harness calls theos's tools over MCP.
	MCP bool
}

// Harness is one agent tool.
type Harness interface {
	// Name is its value in Agent.spec.harness.
	Name() string
	Capabilities() Capabilities
}

// File is a file a harness writes into the project repository.
type File struct {
	// Path is relative to the project repository's root.
	Path string
	Data []byte
}

// LeadFiles is a harness that renders the lead's files for a project, from
// method's content, in its own format. Each file carries Generated where
// its format takes a comment.
type LeadFiles interface {
	Render(p method.Project) ([]File, error)
}

// Generated is the line that marks a file theos writes, as its format
// comments it.
const Generated = "Generated by theos agents from model/; run it again rather than edit this file: " +
	"theos status names a file that changed."

// Drift is a generated file that is not as theos would write it now.
type Drift struct {
	Path string
	// Missing means it isn't there; otherwise it changed.
	Missing bool
}

// Drifted are the files of want that fsys, the project repository, lacks or
// holds otherwise.
func Drifted(fsys fs.FS, want []File) ([]Drift, error) {
	var out []Drift
	for _, f := range want {
		got, err := fs.ReadFile(fsys, f.Path)
		switch {
		case errors.Is(err, fs.ErrNotExist):
			out = append(out, Drift{Path: f.Path, Missing: true})
		case err != nil:
			return nil, err
		case !bytes.Equal(got, f.Data):
			out = append(out, Drift{Path: f.Path})
		}
	}
	return out, nil
}
