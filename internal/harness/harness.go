// Package harness is the interface an agent tool implements to play the
// lead runtime's roles (docs/plans/lead-runtime.md, decision 7): its name,
// the value of Agent.spec.harness, and what it can do. What more a harness
// does is an optional interface a caller asks for, never a harness asked
// for by name. Level 0 is any MCP client, with no code; level 1 renders
// the lead's files (LeadFiles).
package harness

import (
	"bytes"
	"errors"
	"fmt"
	"io/fs"
	"maps"
	"slices"
	"strings"

	"github.com/JairJosafath/theos/internal/method"
)

// Capabilities is what a harness can do.
type Capabilities struct {
	// Subagents means a session starts others for the roles; Parallel that
	// they run at once.
	Subagents, Parallel bool
	// ModelPerRole means each role's subagent runs on its Agent's model.
	ModelPerRole bool
	// MCP means the harness calls theos's tools over MCP.
	MCP bool
}

// Harness is one agent tool.
type Harness interface {
	// Name is its value in Agent.spec.harness.
	Name() string
	Capabilities() Capabilities
}

// File is a file a harness writes into the project repository.
type File struct {
	// Path is relative to the project repository's root.
	Path string
	Data []byte
}

// LeadFiles is a harness that renders the lead's files for a project, from
// method's content, in its own format. Each file carries Generated where
// its format takes a comment.
type LeadFiles interface {
	Render(p method.Project) ([]File, error)
}

// Grants are what a role's agent may do, where a harness enforces it.
type Grants struct {
	// Spawn means it can start other agents; Write that it can change files
	// with the harness's editing tools; Shell that it can run commands, a
	// build among them.
	Spawn, Write, Shell bool
}

// RoleGrants is a harness that enforces each role's tools, and says which
// it gives. A harness that only instructs a role (its boundaries in its
// prompt) has none: its reviewer's boundary is its own word.
type RoleGrants interface {
	Grants(role string) Grants
}

// Roles is one Agent of a project and the roles it plays, in the order the
// Crews first give them.
type Roles struct {
	Agent method.Agent
	Roles []string
}

// AgentRoles are p's Agents, sorted by name, each with the roles it plays
// in any Crew: one subagent, or agent file, per Agent. An Agent given two
// roles one subagent can't keep the boundaries of both of (method.Shares)
// is refused.
func AgentRoles(p method.Project) ([]Roles, error) {
	byName := map[string]*Roles{}
	for _, c := range p.Crews {
		for _, a := range c.Agents {
			r, ok := byName[a.Name]
			if !ok {
				byName[a.Name] = &Roles{Agent: a, Roles: []string{a.Role}}
				continue
			}
			if slices.Contains(r.Roles, a.Role) {
				continue
			}
			if !method.Shares(r.Roles[0], a.Role) {
				return nil, fmt.Errorf("the Agent %s plays the %s and the %s: its one subagent can't have both "+
					"roles' tools and boundaries; give each role an Agent of its own", a.Name, r.Roles[0], a.Role)
			}
			r.Roles = append(r.Roles, a.Role)
		}
	}
	out := make([]Roles, 0, len(byName))
	for _, name := range slices.Sorted(maps.Keys(byName)) {
		out = append(out, *byName[name])
	}
	return out, nil
}

// Boundaries are the boundaries of each role r plays, one after another,
// with a line that says so when there are two.
func (r Roles) Boundaries() string {
	if len(r.Roles) == 1 {
		return method.Boundaries(r.Roles[0])
	}
	parts := make([]string, 0, len(r.Roles))
	for _, role := range r.Roles {
		parts = append(parts, method.Boundaries(role))
	}
	return fmt.Sprintf("Agent %s plays %d roles of theos: each work order names its turn, and each role keeps "+
		"its own rules below.\n\n%s", r.Agent.Name, len(r.Roles), strings.Join(parts, "\n"))
}

// Generated is the line that marks a file theos writes, as its format
// comments it.
const Generated = "Generated by theos agents from model/; run it again rather than edit this file: " +
	"theos status names a file that changed."

// Drift is a generated file that is not as theos would write it now.
type Drift struct {
	Path string
	// Missing means it isn't there; otherwise it changed.
	Missing bool
}

// Drifted are the files of want that fsys, the project repository, lacks or
// holds otherwise.
func Drifted(fsys fs.FS, want []File) ([]Drift, error) {
	var out []Drift
	for _, f := range want {
		got, err := fs.ReadFile(fsys, f.Path)
		switch {
		case errors.Is(err, fs.ErrNotExist):
			out = append(out, Drift{Path: f.Path, Missing: true})
		case err != nil:
			return nil, err
		case !bytes.Equal(got, f.Data):
			out = append(out, Drift{Path: f.Path})
		}
	}
	return out, nil
}
