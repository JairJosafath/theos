// waitingJobPages bounds the pages of queued jobs WaitingJobs reads: an
// organization with more than this many jobs queued at once has a backlog
// no lease clears faster.
const waitingJobPages = 4

// WaitingJobs returns the owner organization's jobs that wait for a runner a
// runner with labels could take, oldest first. Gitea lists a job no runner
// has taken as queued, and one that waits for another job (needs) as
// waiting, which no runner can take yet.
func (g *gitea) WaitingJobs(ctx context.Context, labels []string) ([]ports.WaitingJob, error) {
	var out []ports.WaitingJob
	seen := map[int64]bool{}
	for page := 1; page <= waitingJobPages; page++ {
		query := pageQuery(page)
		query.Set("status", "queued")
		status, data, err := g.do(ctx, http.MethodGet,
			"/api/v1/orgs/"+url.PathEscape(g.owner)+"/actions/jobs?"+query.Encode(), nil)
		if err != nil {
			return nil, err
		}
		var jobs struct {
			Jobs []struct {
				ID        int64     `json:"id"`
				RunID     int64     `json:"run_id"`
				Name      string    `json:"name"`
				Status    string    `json:"status"`
				Labels    []string  `json:"labels"`
				CreatedAt time.Time `json:"created_at"`
				HTMLURL   string    `json:"html_url"`
			} `json:"jobs"`
		}
		if status != http.StatusOK || json.Unmarshal(data, &jobs) != nil {
			return nil, fmt.Errorf("gitea: listing the queued jobs of %q failed (HTTP %d): %s", g.owner, status,
				apiMessage(data))
		}
		for _, j := range jobs.Jobs {
			if seen[j.ID] || j.Status != "queued" || len(j.Labels) == 0 ||
				slices.ContainsFunc(j.Labels, func(l string) bool { return !slices.Contains(labels, l) }) {
				continue
			}
			seen[j.ID] = true
			out = append(out, ports.WaitingJob{ID: j.ID, RunID: j.RunID, Name: j.Name, Labels: j.Labels,
				Created: j.CreatedAt, URL: j.HTMLURL})
		}
		if len(jobs.Jobs) < issuePageSize {
			break
		}
	}
	slices.SortFunc(out, func(a, b ports.WaitingJob) int { return cmp.Compare(a.ID, b.ID) })
	return out, nil
}

// nameField is the field that names a runner, in its registration and in
// its .runner file.
const nameField = "name"

// registeredVersion is the version a runner registered by the operator
// reports until its daemon declares its own.
const registeredVersion = "theos"

// runnerFileWarning is what gitea-runner writes at the top of its .runner
// file.
const runnerFileWarning = "This file is automatically generated by act-runner. Do not edit it manually unless " +
	"you know what you are doing. Removing this file will cause act runner to re-register as a new runner."

// RegisterJobRunner registers an ephemeral runner to the owner organization
// over Gitea's runner protocol, as `gitea-runner register --ephemeral`
// does, with the organization's registration token, and returns what
// gitea-runner reads in model.RemoteRunnerDir: its .runner file, holding
// the runner's own token, which takes one job and goes with the runner
// when Gitea removes it at that job's end, and a config.yaml. Gitea lists
// the labels' names; the .runner file keeps them with their schema.
func (g *gitea) RegisterJobRunner(ctx context.Context, reg ports.RunnerRegistration) (ports.JobRunner, error) {
	token, err := g.RunnerRegistrationToken(ctx)
	if err != nil {
		return ports.JobRunner{}, err
	}
	names := make([]string, len(reg.Labels))
	for i, l := range reg.Labels {
		names[i], _, _ = strings.Cut(l, ":")
	}
	body, err := json.Marshal(map[string]any{nameField: reg.Name, "token": token, "version": registeredVersion,
		"labels": names, "ephemeral": true})
	if err != nil {
		return ports.JobRunner{}, err
	}
	// The runner protocol takes the registration token in its body; the
	// operator's own credential stays off the call.
	req, err := http.NewRequestWithContext(ctx, http.MethodPost,
		g.base.String()+"/api/actions/runner.v1.RunnerService/Register", bytes.NewReader(body))
	if err != nil {
		return ports.JobRunner{}, err
	}
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("Connect-Protocol-Version", "1")
	resp, err := g.http.Do(req)
	if err != nil {
		return ports.JobRunner{}, fmt.Errorf("gitea: registering runner %q of %q: %w", reg.Name, g.owner, err)
	}
	defer func() { _ = resp.Body.Close() }()
	data, err := io.ReadAll(io.LimitReader(resp.Body, 1<<20))
	if err != nil {
		return ports.JobRunner{}, fmt.Errorf("gitea: registering runner %q of %q: %w", reg.Name, g.owner, err)
	}
	var out struct {
		Runner struct {
			ID    int64  `json:"id,string"`
			UUID  string `json:"uuid"`
			Token string `json:"token"`
		} `json:"runner"`
	}
	if resp.StatusCode != http.StatusOK || json.Unmarshal(data, &out) != nil || out.Runner.ID == 0 ||
		out.Runner.UUID == "" || out.Runner.Token == "" {
		return ports.JobRunner{}, fmt.Errorf("gitea: registering runner %q of %q failed (HTTP %d): %s", reg.Name,
			g.owner, resp.StatusCode, apiMessage(data))
	}
	file, err := json.MarshalIndent(map[string]any{"WARNING": runnerFileWarning, "id": out.Runner.ID,
		"uuid": out.Runner.UUID, nameField: reg.Name, "token": out.Runner.Token, "address": reg.Address,
		"labels": reg.Labels, "ephemeral": true}, "", "  ")
	if err != nil {
		return ports.JobRunner{}, err
	}
	config := path.Join(model.RemoteRunnerDir, "config.yaml")
	return ports.JobRunner{ID: out.Runner.ID, Name: reg.Name, Labels: names,
		Files: map[string][]byte{".runner": file, "config.yaml": []byte(jobRunnerConfig(reg.Timeout))},
		Args:  []string{"daemon", "--config", config}}, nil
}

// jobRunnerConfig is gitea-runner's config.yaml for a runner of one job, as
// hack/runner/config.yaml is the pool pods': its .runner file and its
// jobs' folders in model.RemoteRunnerDir, one job at a time, for at most
// timeout (an hour when 0).
func jobRunnerConfig(timeout time.Duration) string {
	minutes := int64(60)
	if timeout > 0 {
		minutes = int64(math.Ceil(timeout.Minutes()))
	}
	return fmt.Sprintf(`log:
  level: info
runner:
  file: %s
  capacity: 1
  timeout: %dm
cache:
  enabled: false
host:
  workdir_parent: %s
`, path.Join(model.RemoteRunnerDir, ".runner"), minutes, path.Join(model.RemoteRunnerDir, "work"))
}
